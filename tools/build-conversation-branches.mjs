import fs from 'node:fs';
const root=new URL('../',import.meta.url),read=p=>fs.readFileSync(new URL(p,root),'utf8');
const topics={};
function add(key,name,title,monologue=false){topics[key]={name,title,monologue,decisions:{}};}
for(const row of read('assets/dialogue/npc-stories.tsv').trim().split('\n')){const [n,...v]=row.split('|');add(n+'/s0',n,v[0]);add(n+'/s1',n,v[4]);}
for(const [n,ts]of Object.entries(JSON.parse(read('assets/dialogue/npc-extra-topics.json'))))ts.forEach((t,i)=>add(n+'/e'+i,n,t.title));
for(const [n,p]of Object.entries(JSON.parse(read('assets/dialogue/npc-world-talks.json')))){
  add(n+'/w0',n,'King Halvard',true);add(n+'/w1',n,'After Halvard’s defeat',true);
  if(p.history)add(n+'/h',n,p.history[0]);
  if(p.roadwork)add(n+'/r',n,p.roadwork[1]);
}
const custom=new URL('assets/dialogue/branch-topics.json',root);
if(fs.existsSync(custom))for(const [key,t]of Object.entries(JSON.parse(fs.readFileSync(custom,'utf8'))))add(key,t.name,t.title,!!t.monologue);
let count=0;
for(const file of fs.readdirSync(new URL('assets/dialogue/branches/',root)).filter(f=>f.endsWith('.tsv')).sort()){
  for(const row of read('assets/dialogue/branches/'+file).split('\n').filter(l=>l.trim()&&!l.startsWith('#'))){
    const [tag,...parts]=row.split('|'),[key,decision='0']=tag.split('#'),t=topics[key];
    if(!t)throw Error('Unknown topic '+tag);
    if(parts.length!==(t.monologue?6:4)||parts.some(s=>!s.trim()))throw Error('Invalid choices '+tag);
    if(t.decisions[decision])throw Error('Duplicate choices '+tag);
    t.decisions[decision]=Array.from({length:parts.length/2},(_,i)=>parts.slice(i*2,i*2+2));count++;
  }
}
const aliases={};for(const [id,t]of Object.entries(topics)){if(id.startsWith('royal/')||id.startsWith('Aurelius/')||id.startsWith('visit/'))continue;const a=t.name+'|'+t.title;if(aliases[a]&&aliases[a]!==id)throw Error('Ambiguous topic '+a);aliases[a]=id;}
fs.writeFileSync(new URL('js/conversation-branch-data.js',root),'/* Generated by tools/build-conversation-branches.mjs. Explicit authored choices only. */\nconst CONVERSATION_BRANCH_DATA='+JSON.stringify({topics,aliases})+';\n');
console.log(count+' authored decision records across '+Object.keys(topics).length+' catalogued topics.');
