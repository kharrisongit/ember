import assert from 'node:assert/strict';
import {loadEditorGame} from '../tools/editor-game-context.mjs';
const {run,context:c}=await loadEditorGame(process.cwd(),{log(){},warn(){}},{furniture:false});
await run('loadPublishedEditorLayouts()');
run(`mode='play';quest=Q.DONE;loadMap('tavern');brambleQuest=3;thornwellRoyal.stage=3;syncBrambleParty();syncThornwellRoyals();
P.x=383;P.y=216;scene=null;ask=null;sayNpc=null;fade=0;fadeDir=0;arriveT=0;
thornwellInviteAudience(thornwellKing());`);
assert(run('!!ask?.conversationPrompt'),'Audience starts with the normal conversation prompt');
const scripts=run('ThornwellAudienceDialogue.rows(thornwellKing())');
assert.equal(scripts.length,8,'The current audience has eight authored topics');
for(const topic of scripts)assert.equal(1+topic.authoredBranches.decisions[0].length,3,'Every topic has three complete reply branches');
assert.match(JSON.stringify(scripts),/fifty years/);assert.match(JSON.stringify(scripts),/dragon/);
run(`ThornwellAudienceDialogue.rows(thornwellKing()).find(t=>t.title==='What gave you the right to rule?').onReply('You chose to attack people who trusted you.')`);
assert.equal(run('thornwellRoyal.answers.conquest'),'defiant','Audience choices update the saved response');
run(`restoreThornwellRoyal({stage:4,answers:{conquest:'defiant',hunt:'question'}})`);
assert.equal(run('captureThornwellRoyal().answers.conquest'),'defiant');assert.equal(run('captureThornwellRoyal().answers.hunt'),'question');
run(`scene=null;ask=null;sayNpc=null;walker=null;doorMotion=null;fade=0;fadeDir=0;arriveT=0;P.x=256;P.dir='d';P.moving=true;`);
for(const y of [312,320,328,334,335]){c.edgeY=y;run('P.y=edgeY;useDoors(0)');assert.equal(run('doorMotion'),null,'No exit before the edge at '+y);}
run('P.y=336;useDoors(0)');assert(run('doorMotion?.d.to==="world"'),'Exit begins at the last visible floor pixel');
console.log('PASS: Current royal audience prompts, eight complete topics and persisted choices, and the tavern exit waits for the floor edge.');
