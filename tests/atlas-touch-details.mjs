import assert from 'node:assert/strict';
import {loadEditorGame} from '../tools/editor-game-context.mjs';
import {gameDom} from './helpers-game-dom.mjs';
const dom=gameDom(),{run}=await loadEditorGame(process.cwd(),{log(){},warn(){}},{document:dom.document,furniture:false});
run(`quest=Q.DONE;dragon.on=true;dragonOff=false;templeCompass.owned=true;templeCompass.mapGiven=true;MAPID='world';P.x=30*TS;P.y=425*TS;atlasBegin()`);
const details=dom.element('atlasDetails'),view=dom.element('atlasViewport');view.setPointerCapture=()=>{};
assert.equal(dom.element('atlasName').textContent,'Millwood');
assert(dom.element('atlasAnimation').classList.contains('active'),'Opening the map starts environmental animation');
assert.equal(dom.element('atlasAnimation').getAttribute('aria-hidden'),'true');
assert(!details.classList.contains('details-expanded'),'Map opens compact on the current area');
assert(!dom.element('atlasPlaces').children.some(b=>b.getAttribute('aria-label')==='Explore Ice Moth'),'Unvisited boss remains hidden in the overview');
run("atlasRevealPlace('Sandspire');atlasBuildPlaces();atlasRenderFog()");
const place=dom.element('atlasPlaces').children.find(b=>b.getAttribute('aria-label')==='Explore Sandspire');
const fire=(type,extra={})=>{for(const fn of view.listeners.get(type)||[])fn({type,button:0,pointerId:1,clientX:0,clientY:0,target:place,preventDefault(){},...extra});};
run('atlasPan={x:0,y:0,z:1}');fire('pointerdown');fire('pointerup');
assert(details.classList.contains('details-expanded'));
assert.equal(dom.element('atlasName').textContent,'Sandspire');
assert.match(dom.element('atlasText').textContent,/dry sandstone/);
fire('pointerdown');fire('pointermove',{clientX:50});fire('pointerup',{clientX:50});
assert(!details.classList.contains('details-expanded'),'Panning returns space to the map');
assert.equal(dom.element('atlasName').textContent,'Sandspire','Panning does not change the selected area');
fire('pointerdown');fire('pointerup');assert(details.classList.contains('details-expanded'));
fire('wheel',{deltaY:-80});assert(!details.classList.contains('details-expanded'),'Zooming also compacts the panel');
run(`atlasSelectPlace(0);atlasShowWhole()`);assert(!details.classList.contains('details-expanded'));
assert(run(`ATLAS_LOCATIONS.find(p=>p[0]==='Coralmere')[1]>ATLAS_LOCATIONS.find(p=>p[0]==='Sandspire')[1]+100`),'Coralmere is farther east');
assert(run(`ATLAS_LOCATIONS.find(p=>p[0]==='Northern Shroom Field')[2]<ATLAS_LOCATIONS.find(p=>p[0]==='Sporehollow')[2]-60`),'Northern field has space above the village');
run(`odoRodReferral=true;fishingPole=false;atlasSyncJournal();atlasTrack('fishing')`);
assert(!dom.element('atlasAnimation').classList.contains('active'),'Tracking closes the map and pauses its animation');
assert(dom.element('toast').classList.contains('compass-safe'),'Tracking uses the compass-safe toast placement');
console.log('PASS: area-first map, expanded area taps, compact pan/zoom/whole realm, corrected geography and compass-safe tracking notice.');
