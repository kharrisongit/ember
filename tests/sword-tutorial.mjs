import assert from 'node:assert/strict';
import {loadEditorGame} from '../tools/editor-game-context.mjs';
import {gameDom} from './helpers-game-dom.mjs';
const dom=gameDom();
const {run,context:c}=await loadEditorGame(process.cwd(),{log(){},warn(){},error:console.error},{furniture:false,document:dom.document});
run(`MAPID='world';MD=W.maps.world;features=MD.features;quest=Q.ARMED;mode='play';gameplayStarted=true;
scene=null;revealing=false;fadeDir=0;fade=0;P.act=null;dragon.on=false;
canStand=()=>true;dragonCanStand=()=>true;rebuildSolid=()=>{};rebuildBuckets=()=>{};clampCam=()=>{};
MW=4000;MH=600;solid=new Uint8Array(MW*MH);terr=new Uint8Array(MW*MH);blockedByNpcBody=()=>false;blockedByNpcBuffer=()=>false;
stepChest=()=>{};stepHuntingGrounds=()=>{};saveGame=()=>{};showScene=()=>{};typeDone=()=>true;
const swordRing=features.find(a=>a.id===208);
P.x=swordRing.x*TS;P.y=(swordRing.y+swordRing.r+2)*TS;
foes=[{kind:'ghost',x:swordRing.x*TS,y:swordRing.y*TS,hp:8,st:'approach',t:0,dir:'s'},
{kind:'ghost',x:swordRing.x*TS+20,y:swordRing.y*TS+10,hp:8,st:'idle',t:0,dir:'s'}];
currentArenaFeatures=()=>[swordRing];EmberRiding.restore({quest:Q.ARMED});`);
assert(run('hasSword()'),'Corin still carries the sword before the tutorial');
assert.equal(run('corinKit()'),'corin_sword_','The equipped sword remains visible');
run('startAct("swing")');assert.equal(run('P.act'),null,'Sword attacks are locked before the tutorial');
dom.touch(dom.element('act'));assert.equal(run('P.act'),null,'The real A control cannot swipe early');
assert(run('foes.every(f=>f.ridingArena===208&&f.st==="idle"&&f.y===swordRing.y*TS+TS)'),
  'First northern arena enemies wait near the center, within sight');
const waiting=run('JSON.stringify(foes.map(f=>[f.x,f.y,f.hp]))');
for(let i=0;i<60;i++)run('stepFoes(.05)');
assert.equal(run('JSON.stringify(foes.map(f=>[f.x,f.y,f.hp]))'),waiting,'Enemies never jump on approach');
run('quest=Q.NOISE;EmberRiding.entered(swordRing)');assert(!run('EmberRiding.holding()'),'Sword required');
run('quest=Q.ARMED;P.y=(swordRing.y+swordRing.r-1.1)*TS;stepArena(.01)');
assert(run('EmberRiding.holding()'));assert.equal(run('scene'),null,'Wait for walls to rise');
assert.equal(run('JSON.stringify(foes.map(f=>[f.x,f.y,f.hp]))'),waiting,'Entry does not reposition enemies');
run('stepArena(.4);EmberRiding.step(.4)');
assert.equal(run('scene.lines[0]'),"Corin: What are these walls? I can’t escape! I have to fight!");
assert.equal(run('scene.hidePortrait'),true,'The trapped reaction leaves the battlefield visible');
run('startAct("swing")');assert.equal(run('P.act'),null,'Attacks stay locked during Corin’s dialogue');
for(let i=0;i<20;i++)run('stepCombat(.05)');
assert.equal(run('JSON.stringify(foes.map(f=>[f.x,f.y,f.hp]))'),waiting,'Enemies wait through dialogue');
run('scene.t=1');dom.touch(dom.element('act'));
assert.equal(run('scene'),null);assert.equal(dom.element('ridingHint').dataset.instruction,'Press A to Swing Your Sword');
assert(dom.element('ridingHint').classList.contains('combat-prompt'),'Swipe uses the prominent combat card');
assert(run('EmberRiding.holding()'));assert.equal(run('P.act'),null,'Dialogue dismissal does not perform the swipe');
assert(dom.element('act').classList.contains('riding-target'));
run('setOvl("itemm")');assert.equal(run('ovl'),null,'Other controls cannot bypass the tutorial');
dom.touch(dom.element('act'));
assert.equal(run('P.act'),null,'Dismissing the lesson consumes A without an accidental attack');
assert(!run('EmberRiding.holding()'));assert(run('EmberRiding.capture().swordDone'));
assert(run('foes.every(f=>!EmberRiding.waitingEnemy(f))'),'Enemies activate immediately');
dom.touch(dom.element('act'));
assert.equal(run('P.act.kind'),'swing','The next A press performs the taught sword attack');
run('P.act=null;startAct("swing")');assert.equal(run('P.act.kind'),'swing','Further sword attacks stay unlocked');
run('stepFoes(.05)');assert(run('foes.some(f=>f._thinking)'),'Normal enemy AI resumes');
run('pHp=pMax;pInv=0;foes[0].x=P.x;foes[0].y=P.y-16;P.act={kind:"swing",t:4,dir:"u",flip:false,dir8:"n"};swingHits()');
assert.equal(run('pHp'),run('pMax-1'),'The first real sword exchange costs one heart');
assert.equal(run('P.act.kind'),'hurt','The tutorial graze has a hurt animation');
run('P.act={kind:"swing",t:4,dir:"u",flip:false,dir8:"n"};swingHits()');
assert.equal(run('pHp'),run('pMax-1'),'The scripted graze happens only once');
run('pInv=0;hurtPlayer(99)');assert.equal(run('pHp'),1,'First sword battle cannot kill Corin before the healing lesson');
run('pHp=pMax-1;potions=0;hareMeat=2;foes.forEach(f=>f.st="dead");scene=null');
for(let i=0;i<30&&!run('scene');i++)run('stepArena(.05)');
assert.equal(run('EmberRiding.capture().phase'),'corinHealTalk');
assert(run('potions===1&&EmberRiding.blocksArenaEntry()'),'Recovery supplies a potion and prevents re-entry');
const finish=()=>run('{const next=scene.after;scene=null;next?.();}');
finish();assert(dom.element('btnItems').classList.contains('riding-target'));
dom.touch(dom.element('btnItems'));
assert.equal(run('EmberRiding.capture().phase'),'corinHeal');
assert(run('MENUS.itemm.items().filter(it=>EmberRiding.allowedItem("itemm",it)).every(it=>it.key==="potion")'),'Only Potion advances the lesson');
run('setOvl(null)');assert.equal(run('ovl'),'itemm','Cannot dismiss the required healing choice');
c.recovery=run('({quest:Q.ARMED,ridingTutorial:EmberRiding.capture()})');
run('scene=null;potions=0;EmberRiding.restore(recovery);EmberRiding.step(.05)');
assert.equal(run('EmberRiding.capture().phase'),'corinHealTalk','Reload resumes Corin’s unfinished lesson');
assert(run('potions===1&&cooling.has("world:208")'),'Reload has a potion and keeps the arena cleared');
finish();dom.touch(dom.element('btnItems'));
const potionIndex=run('MENUS.itemm.items().findIndex(it=>it.key==="potion")');
dom.touch(dom.element('itemRows').children[potionIndex]);
assert(run('pHp===pMax&&potions===0'),'The real potion restores health and is consumed');
assert.equal(run('EmberRiding.capture().phase'),'corinThanks');finish();
assert(run('EmberRiding.capture().corinHealDone&&!EmberRiding.holding()'),'Potion lesson releases controls');
c.saved=run('({quest:Q.ARMED,ridingTutorial:EmberRiding.capture()})');
run('EmberRiding.restore(saved);EmberRiding.entered(swordRing)');assert(!run('EmberRiding.holding()'),'Completed lesson stays completed on reload');
assert(run('EmberRiding.canSwipe()'),'Save restoration preserves sword use');
run('EmberRiding.restore({quest:Q.FLED});EmberRiding.entered(swordRing)');assert(!run('EmberRiding.holding()'),'Later legacy saves do not repeat the lesson');
run('EmberRiding.restore({quest:Q.ARMED,ridingTutorial:{version:2,swordDone:false}});EmberRiding.entered(swordRing)');
assert.equal(run('EmberRiding.capture().phase'),'swordWalls','An incomplete lesson restarts safely');
run('P.act=null;startAct("swing")');assert.equal(run('P.act'),null,'Incomplete saves keep sword attacks locked');
run('EmberRiding.skip()');assert(run('EmberRiding.capture().swordDone'));assert(!run('EmberRiding.holding()'));
console.log('PASS: sword arena stages enemies before entry, waits through walls and Corin’s line, teaches a real A swipe, resumes AI, and preserves completion across saves.');
