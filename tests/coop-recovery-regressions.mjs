import assert from 'node:assert/strict';
import fs from 'node:fs';
import {loadEditorGame} from '../tools/editor-game-context.mjs';
import {gameDom} from './helpers-game-dom.mjs';
const dom=gameDom();
const {run,context:c}=await loadEditorGame(process.cwd(),{log(){},warn(){},error:console.error},{furniture:false,document:dom.document});
const json=s=>JSON.parse(run('JSON.stringify('+s+')'));
run(`mode='play';quest=Q.DONE;gameplayStarted=true;loadMap('house22');[P.x,P.y]=MD.spawn;
window.LDRCoopRender={enable(){}};window.EmberArenaEntry=undefined;window.EmberRiding=undefined;window.EmberEquipmentTutorial=undefined;
EmberCloudState.activate('host');
var hosting=true,uid='host',campaignId='recovery-test',cloudSlot=0,latestSave=null,pendingSave=false,saveAt=0,commandSeq=0;
var notices=[],sent=[],room={send:(type,data)=>sent.push({type,data})},notice=text=>notices.push(text);
var owner=()=>EmberCloudState.owner,key=()=> 'ldr.coop.campaigns.'+owner();
var localSaves=()=>JSON.parse(localStorage.getItem(key())||'[]');`);
// Keep the actual campaign persistence and checkpoint functions. Only transport
// is replaced; local/account storage and the Save & exit button are real.
const campaign=fs.readFileSync(new URL('../js/coop-campaign.js',import.meta.url),'utf8');
run(campaign.slice(campaign.indexOf('  function persist('),campaign.indexOf('  async function connect(')));
run(`var players=[{uid:'host',profile:{name:'Host'}},{uid:'guest',profile:{name:'Guest'}}];`);
await run(`LDRCampaign.start({uid:'host',players,onNotice:notice,onSave:checkpoint})`);
const clear=()=>run(`scene=null;sayNpc=null;revealing=false;ovl=null;ask=null;arenaLock=null;foes=[];fadeDir=0;doorMotion=null;bossScene=null;deadShown=false;`);
clear();
assert(run('checkpoint()'));
const baseline=json('latestSave');
run(`gold+=100;arenaLock={id:77,x:8,y:8,r:6};arenaT=1;var reloads=0;location.reload=()=>reloads++;EmberCloud.manage();`);
const exit=()=>dom.dispatch(c.document.body.querySelectorAll('button').find(n=>n.textContent==='Save & exit to title'),'click');
exit();
assert.equal(run('reloads'),0,'Save & exit must not reload while the checkpoint is queued');
assert(run('pendingSave'));assert.deepEqual(json('latestSave'),baseline);
assert(run('notices.some(n=>/Save queued/.test(n))'));
assert(c.document.body.querySelectorAll('p').some(n=>/Save did not complete/.test(n.textContent)));
clear();
const setItem=c.localStorage.setItem;
c.localStorage.setItem=()=>{throw Error('Storage is full');};exit();
assert.equal(run('reloads'),0,'A storage failure also keeps the game open');
c.localStorage.setItem=setItem;
exit();
assert.equal(run('reloads'),1,'A successful retry can exit');
assert.equal(json('localSaves()[0].save.gold'),baseline.save.gold+100);
assert.equal(run('readSaveSlot(cloudSlot).gold'),baseline.save.gold+100);
assert(!run('pendingSave'));
run(`hosting=false;`);assert.equal(run('checkpoint(true)'),false,'A remote save request is not a completed local save');run('hosting=true');
console.log('PASS: actual Save & exit stays open for deferred/failed saves, retries persist before reload, and remote requests do not report completion.');
dom.element('cloudSaveDialog').close();
for(const fallen of ['host','guest']){
 const living=fallen==='host'?'guest':'host';clear();
 run(`LDRCampaign.withActor('${living}',()=>{pHp=6;P.act=null;P.x=128;P.y=192;});
 LDRCampaign.withActor('${fallen}',()=>{pHp=0;P.act={kind:'die',t:6.99,done:1};P.x=170;P.y=192;});`);
 c.previous=json('LDRCampaign.checkpoint()');assert(c.previous);
 await run(`LDRCampaign.start({uid:'host',players,checkpoint:previous,onNotice:notice,onSave:checkpoint})`);
 assert.equal(run(`LDRCampaign.actor('${fallen}').vars.pHp`),0);
 assert.equal(run(`LDRCampaign.actor('${fallen}').P.act.kind`),'die');
 run(`LDRCampaign.withActor('${fallen}',()=>{padDx=1;padDy=0;arriveT=0;var x=P.x;stepAct(.1);stepPlayer(.1);globalThis.moved=P.x!==x;});`);
 assert(!run('moved'),'A restored fallen rider cannot walk');
 run(`LDRCampaign.withActor('${fallen}',()=>{P.x=280;P.y=192;});LDRCampaign.claim('${living}','action');playScene(['Corin: Shared scene.']);`);
 assert.equal(run(`LDRCampaign.actor('${fallen}').P.act.kind`),'die','Scene regrouping preserves the downed pose');
 clear();
 run(`LDRCampaign.withActor('${fallen}',()=>{P.act=null;padDx=1;P.moving=true;var x=P.x;stepPlayer(.1);globalThis.moved=P.x!==x;});`);
 assert(!run('moved'),'Zero health blocks movement even if another effect clears the animation');
 run(`LDRCampaign.withActor('${living}',()=>{const other=LDRCampaign.actor('${fallen}');P.x=other.P.x-20;P.y=other.P.y;});LDRCampaign.command('${living}','revive');`);
 assert.equal(run(`LDRCampaign.actor('${fallen}').vars.pHp`),3);
 run(`LDRCampaign.withActor('${fallen}',()=>{P.x=128;P.y=192;padDx=1;padDy=0;arriveT=0;var x=P.x;stepPlayer(.1);globalThis.moved=P.x!==x;});`);
 assert(run('moved'),'A revived rider moves normally again');
}
console.log('PASS: fallen host/guest stays down after resume and scene regrouping, movement respects health, and partner revival restores movement.');
