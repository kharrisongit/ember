import fs from 'node:fs';import zlib from 'node:zlib';import vm from 'node:vm';import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('js/generated/game-part-1.js'),code=read('js/generated/game-part-2.js');
const W=JSON.parse(zlib.gunzipSync(Buffer.from(source.match(/const W_GZ = "([^"]+)/)[1],'base64')));
const c=vm.createContext({W}),run=s=>vm.runInContext(s,c);
run(code.slice(code.indexOf('function restoreTavernCast('),code.indexOf('function restoreSchoolCast(')));
run(code.slice(code.indexOf('function tavernActorDepth('),code.indexOf('function drawMarketActor(')));
run('restoreTavernCast()');
const room=W.maps.tavern;
const layout=JSON.parse(read('assets/interiors/remaining/layouts.json')).tavern;
for(const f of layout.objects)room.roomActors.push({n:f.name.replaceAll('-',' '),x:f.x+f.w/2,y:f.y+f.h,sy:f.sortY??f.y+f.h,sourceRect:[f.x,f.y,f.w,f.h],extractedCanvas:{width:f.w,height:f.h},exactFurniture:true});
const depth=o=>c.tavernActorDepth(o,room.roomActors);
const bartender=room.roomActors.find(a=>a.spr==='tavern_anim_9'),shelf=room.roomActors.find(a=>a.n==='bottle cabinet'),counter=room.roomActors.find(a=>a.n==='bar counter');
assert(depth(shelf)<depth(bartender),'Bartender in front of back shelf');assert(depth(bartender)<depth(counter),'Bartender stays behind bar counter');
const dancer=room.roomActors.find(a=>a.spr==='tavern_anim_14'),table=room.roomActors.find(a=>a.n==='dining table'&&a.x===177.5);
assert(depth(dancer)>depth(table),'Dancing lizard on tabletop');
const hobb=room.roomActors.find(a=>a.spr==='tavern_anim_8'),chair=room.roomActors.find(a=>a.n==='stool'&&a.x===161.5&&a.y===174);
assert(depth(chair)<depth(hobb),'Chair beneath seated patron');
chair.y+=8;chair.sy+=8;assert(depth(chair)<depth(hobb),'Nearby moved chair stays beneath patron');
chair.x+=1000;assert.equal(depth(chair),chair.sy,'Unoccupied chair returns to its own depth');
table.x+=100;assert.equal(depth(dancer),dancer.y,'Moving table away releases dancer depth');
console.log('PASS: actual tavern cast and furniture sort bartender before counter/after shelf, dancer above table, and patrons above chairs; independent furniture movement is respected.');
