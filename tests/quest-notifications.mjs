import assert from 'node:assert/strict';
import {loadEditorGame} from '../tools/editor-game-context.mjs';
import {gameDom} from './helpers-game-dom.mjs';
const dom=gameDom(),{run,context:c}=await loadEditorGame(process.cwd(),{log(){},warn(){}},{document:dom.document,furniture:false});
const text=node=>[node.textContent,...node.children.flatMap(child=>text(child))];
const state=()=>JSON.parse(run('JSON.stringify(EmberQuestNotifications.capture())'));
run(`gameplayStarted=true;mode='play';BOOT.waiting=false;MAPID='world';MD=W.maps.world;quest=Q.ARMED;
scene=null;sayNpc=null;ask=null;revealing=null;atlasOpen=false;bagOpen=false;ovl=null;bossScene=null;deadShown=false;
fade=0;fadeDir=0;P.act=null;arenaLock=null;templeCompass.owned=true;templeCompass.mapGiven=true;
odoRodReferral=false;fishingPole=false;brambleQuest=0;thornwellRoyal.stage=0;dragonIntroDone=false;
dragonBanterSeen.clear();saveGame=()=>{};EmberEquipmentTutorial.skip();EmberRiding.skip();
EmberFriendship.restore({tutorialSeen:true});EmberQuestNotifications.restore({version:1,seen:[],pending:[]});`);
// Discoveries are journaled silently; this intentionally replaces the old
// automatic NEW QUEST card, including any queued notifications in older saves.
const silent=()=>{assert.equal(state().pending.length,0);const card=c.document.body.querySelector('#questUnlockNotice');assert(!card||card.hidden);};
run('odoRodReferral=true;atlasSyncJournal();EmberQuestNotifications.scan()');
assert(run("atlasQuestOptions().some(q=>q.id==='fishing')"));
assert(state().seen.includes('fishing'));silent();
run('scene={};ask={npcConversation:"Odo",opts:[]};EmberQuestNotifications.tick(1000)');
assert(run('!!scene&&ask.npcConversation==="Odo"'),'Discovery preserves the active conversation');silent();
c.saved=JSON.parse(run('JSON.stringify(captureQuestJournal())'));
run('restoreQuestJournal(saved);EmberQuestNotifications.tick(6000)');silent();
run('restoreQuestJournal({known:{}});EmberQuestNotifications.tick(6500)');silent();
assert(state().seen.includes('fishing'),'Old saves establish the current journal baseline');
run(`rememberDragonKnowledge('Mira','Ask Sverre for Torvald’s lantern in Hollybeck.',false);EmberQuestNotifications.tick(7000)`);
assert(run("atlasQuestOptions().some(q=>q.id==='gift:lamp')"));silent();
run('quest=Q.DONE;dragonIntroDone=true;EmberQuestNotifications.tick(12500)');
assert(run("atlasQuestOptions().filter(q=>q.id.startsWith('temple:')).length===3"));silent();
run('breathHas.lightning=true;EmberQuestNotifications.tick(18000)');silent();
run(`EmberQuestNotifications.restore({version:1,seen:['fishing'],pending:[{key:'fishing',id:'fishing',title:'Calder’s spare rod',detail:'Ask Calder'}]});EmberQuestNotifications.tick(20000)`);
silent();assert(state().seen.includes('fishing'),'Legacy queued events retain discovery history without replaying');
run('templeCompass.mapGiven=false;EmberQuestNotifications.tick(21000);templeCompass.mapGiven=true;EmberQuestNotifications.tick(21500)');silent();
// Quest labels come from actual unlock state, with ordinary leads separately marked.
run(`scene=null;askShut();charm.lamp=false;dragonBanterSeen.delete('learned:lantern');openNpcTopics({n:'Mira',x:100,y:100});EmberConversationFlow.openChat();`);
assert(run('ask.opts.some(o=>o.questUnlock)'));assert(dom.element('bagAsk').querySelector('.deckTopic-newQuest'));
assert(text(dom.element('bagAsk')).includes('New quest'));
run(`rememberDragonKnowledge('Mira','Ask Sverre for Torvald’s lantern.',false);openNpcTopics({n:'Mira',x:100,y:100});EmberConversationFlow.openChat()`);
assert(!run('ask.opts.some(o=>o.questUnlock)'),'Known quest loses new-quest label');
assert(text(dom.element('bagAsk')).includes('Quest lead'));
console.log('PASS: silent quest discovery, preserved dialogue, journal progression, save/reload and legacy notification migration.');
