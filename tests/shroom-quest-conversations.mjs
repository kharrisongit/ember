import assert from 'node:assert/strict';
import {loadEditorGame} from '../tools/editor-game-context.mjs';
import {gameDom} from './helpers-game-dom.mjs';
const dom=gameDom(),{run,context:c}=await loadEditorGame(process.cwd(),{log(){},warn(){}},{furniture:false,document:dom.document});
const box=dom.element('bagAsk');box.appendChild(dom.element('askRows'));
run(`mode='play';gameplayStarted=true;MAPID='world';MD=W.maps.world;MW=MD.w;MH=MD.h;terr=new Uint8Array(MW*MH);
 quest=Q.ARMED;P.act=null;scene=null;ask=null;sayNpc=null;ride=null;doorMotion=null;EmberRiding.skip();
 EmberFriendship.restore({tutorialSeen:false});prepareShroomLookoutData(MD,'world');
 var mosslet=MD.npcs.find(n=>n.mainPathLookout),king=MD.npcs.find(n=>n.n==='The Shroom King');
 saveGame=()=>{};dragonConversationReaction=()=>{};`);
// Use the actual interaction router, not just the clue/service helper.
for(const name of ['interactTrialPedestal','tryFerrySign','ferryTry','tryHouseLootChest','tryTreasuryChest','tryExpandedTempleLever','tryTempleLever','tryCellarSupplies','tryChest','itemAt','questTalk'])c[name]=()=>false;
run('Crafting.gather=()=>false');
const finishScene=()=>run('for(let i=0;i<20&&scene;i++){typeAll();scene.t=1;advanceScene();}');
run('npcs=[mosslet];P.x=mosslet.x;P.y=mosslet.y+20;P.dir="u";interact();');
assert(run('scene.lines.some(l=>l.includes("Speak with the Shroom King"))'));
assert(!run('ask||EmberConversationFlow.active()'),'Mosslet gives the clue in the world before any panel');
assert(run('!!portraitFor("Mosslet")'),'His overworld and full-screen portraits both resolve');
assert.equal(run('EmberConversationView.profile("Mosslet",mosslet).role'),'Lookout','Sharing portrait art must not replace his own profile');
assert(!run('discussedTopics.has("Mosslet:crash")'),'Do not record an unfinished clue');
finishScene();assert(run('discussedTopics.has("Mosslet:crash")'));
run('npcs=[king];P.x=king.x;P.y=king.y+20;interact()');
assert(run('sayNpc===king&&!ask&&!EmberConversationFlow.active()'),'First King interaction automatically starts his offer');
assert(!run('charm.spore'),'Finish the offer before granting the spore');
let gifts=0;c.showReveal=()=>{gifts++;run('revealing=true');};
run('for(let i=0;i<12&&sayNpc;i++){typeAll();interact();}');
assert(run('charm.spore&&EmberEquipmentTutorial.capture().pending'),'Grant the spore and queue its tutorial');
assert.equal(gifts,1);
run('revealing=false;EmberEquipmentTutorial.skip();interact()');finishScene();
assert(run('ask.conversationPrompt'),'After the gift, optional full conversations remain available');
run('askPick=1;askTake()');
assert(run('EmberConversationPanels.isOpen()'));
run('askDraw()');
assert.equal(box.querySelectorAll('.conversationFullPanel').length,1,'Redraw must not detach an active tutorial');
assert.equal(box.querySelector('.conversationPlayer').getAttribute('inert'),'');
box.querySelector('.conversationPanelFooter').querySelector('button').onclick({stopPropagation(){}});
assert(!run('EmberConversationPanels.isOpen()'));
assert.equal(box.querySelector('.conversationPlayer').getAttribute('inert'),undefined);
box.querySelector('.conversationChat').onclick({stopPropagation(){}});
const storyIndex=run('ask.opts.findIndex(o=>o.friendshipId==="renewal-v2-0")');
box.querySelectorAll('.deckTopic').find(b=>Number(b.dataset.askIndex)===storyIndex).onclick({stopPropagation(){}});
assert(run('scene?.conversationReplies'),'King topics start normally');
run('typeAll();scene.t=1;EmberConversationFlow.next()');
assert.equal(box.querySelectorAll('.deckReply').length,3);
box.querySelectorAll('.deckReply')[1].onclick({stopPropagation(){}});
assert.equal(run('typeWho'),'Corin');
run('typeAll();scene.t=1;EmberConversationFlow.next();typeAll();scene.t=1;EmberConversationFlow.next()');
assert.equal(gifts,1,'Optional topics never grant a duplicate gift');
run('scene=null;sayNpc=null;askShut();quest=Q.FLED;EmberConversationFlow.prompt(mosslet)');
assert(run('scene.lines.some(l=>/tell our king/i.test(l))&&!EmberConversationFlow.active()'));
finishScene();assert(run('discussedTopics.has("Mosslet:return")'));
run('EmberConversationFlow.prompt(mosslet)');finishScene();
assert(run('ask.conversationPrompt'),'Mosslet keeps optional conversations after both required clues');
console.log('PASS: real Shroom interaction routing, overworld clue/gift, once-only reward/tutorial, Mosslet portrait, optional topics/replies and redraw-safe help.');
