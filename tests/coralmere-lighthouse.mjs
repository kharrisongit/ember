import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const c=vm.createContext({console});
vm.runInContext(`
var MAPID='world',TS=16,MW=2100,GRASS=0,DIRT=1,NAMES=['agrass1','pinkf0','dtuft0'];
var terr=new Uint8Array(MW*540),chunks={clear(){}},decorGone=new Set();
var MD={doors:[{to:'house42',x:2014,y:512},{to:'house43',x:2026,y:512},{to:'house44',x:2034,y:511,oy:11},{to:'house45',x:2041,y:511,oy:12}]};
var doorRect=d=>({x:d.x*16,y:d.y*16+(d.oy||0),w:16,h:16});
var features=[{kind:'route',style:'blossom',w:5,band:8,pts:[[20,20],[40,20]]}];
var routeLegs=f=>[[f.pts[0],f.pts[1]]];
var sanm=[0,30*16,22*16,1,30*16,22*16,0,80*16,80*16];
var fsanim=[...sanm,2,30*16,22*16];
var art={test:'canvas'},furniture={test:'furniture canvas'};
var W={maps:{millwood_mill:{w:14,h:14,_roomBaseCanvas:art,roomActors:[{extractedCanvas:furniture,moveBlocks:[0]}],roomBlocks:[[1,2,3,4]],doors:[{to:'world',tx:14,ty:431},{to:'millwood_mill_loft'}]},millwood_mill_loft:{roomActors:[],doors:[{to:'millwood_mill'}]}}};
`,c);
vm.runInContext(fs.readFileSync('js/coralmere-lighthouse.js','utf8')+'\nCoralmereLighthouse.installInteriors();CoralmereLighthouse.repairPaths();',c);
const room=c.W.maps.coralmere_lighthouse,mill=c.W.maps.millwood_mill;
assert.equal(room._roomBaseCanvas,mill._roomBaseCanvas);
assert.equal(room.roomActors[0].extractedCanvas,mill.roomActors[0].extractedCanvas);
room.roomActors[0].moveBlocks.push(1);room.roomBlocks[0][0]=9;
assert.equal(mill.roomActors[0].moveBlocks.length,1);
assert.equal(mill.roomBlocks[0][0],1);
assert.equal(room.doors[0].tx,2053);
assert.equal(room.doors[1].to,'coralmere_lighthouse_loft');
assert.equal(c.W.maps.coralmere_lighthouse_loft.doors[0].to,'coralmere_lighthouse');
for(const x of [2014,2020,2026,2034,2041])for(let y=512;y<=517;y++)assert.equal(c.terr[y*c.MW+x],1,'Approaches connect every doorstep and the north road');
for(let x=2013;x<=2054;x++)assert.equal(c.terr[517*c.MW+x],1,'Waterfront path stays continuous');
assert.equal(c.terr[518*c.MW+2014],0,'Dock terrain is untouched');
vm.runInContext(fs.readFileSync('js/blossom-routes.js','utf8')+'\nclearBlossomTufts();',c);
assert.deepEqual([...c.decorGone],['a0'],'Only blossom tufts are hidden; authored indices remain stable');
assert.deepEqual([...c.fsanim],[1,480,352,0,1280,1280],'Flowers and other regions survive');
vm.runInContext('clearBlossomTufts()',c);
assert.equal(c.fsanim.length,6,'Cleanup is idempotent');
console.log('PASS: independent lighthouse rooms, connected house paths, scoped blossom tuft removal.');
